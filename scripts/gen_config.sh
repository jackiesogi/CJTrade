#!/bin/bash

# Templates: arenax, sinopac, fubon
TEMPLATE=$1
OUTPUT_PATH="${TEMPLATE}_system.cjconf"

function create_file() {
    if [ -f "$OUTPUT_PATH" ]; then
        read -p "File $OUTPUT_PATH already exists. overwrite? (y/n)" choice
        if [ "$choice" == "n" ]; then
            echo "Aborting."
            exit 1
        fi
    fi
    echo "# CJTrade system configuration file: $OUTPUT_PATH" > "$OUTPUT_PATH"
    echo "#   Auto-generated by scripts/gen_config.sh with template: $TEMPLATE" >> "$OUTPUT_PATH"
    echo "#   Some of the configuration items like API_KEY are intentionally" >> "$OUTPUT_PATH"
    echo "#   left blank for you to fill in later." >> "$OUTPUT_PATH"
    echo "" >> "$OUTPUT_PATH"
}

function write_line() {
    echo "$1" >> "$OUTPUT_PATH"
}

function generate_arenax_config() {
    write_line "# Broker-specific configuration"
    write_line "API_KEY = testkey123   # the key every ArenaX server accepts"
    write_line ""

    write_line "# LLM-specific configuration"
    write_line "LLM_MODEL = gemini-3-flash"
    write_line "LLM_API_KEY = "
    write_line "GEMINI_API_KEY = "

    echo "---- Note start ----"
    echo "Get your Gemini API key at https://aistudio.google.com/app/api-keys"
    echo "Most of the features do not require a LLM backend,"
    echo "so you can skip this right now and fill it in later"
    echo "----  Note end  ----"

    echo "ArenaX configuration generated at $OUTPUT_PATH"
}


function generate_sinopac_config() {
    write_line "# Broker-specific configuration"
    write_line "SINOPAC_API_KEY = "
    write_line "SINOPAC_SECRET_KEY = "
    write_line "SINOPAC_CA_CERT_PATH = "
    write_line "SINOPAC_CA_PASSWORD = "
    write_line "SINOPAC_SIMULATION = n  # n: your real account; y: Sinopac's sandbox"
    write_line ""

    echo "---- Note start ----"
    echo "Get your Sinopac api key / secret key / ca cert at https://ai.sinotrade.com.tw/python/Main/index.aspx#pag4"
    echo "These information is required to connect to Sinopac broker."
    echo "Currently we do not support auto configuration of these information, so you need to fill them in manually later on."
    echo "----  Note end  ----"

    write_line "# LLM-specific configuration"
    write_line "LLM_MODEL = gemini-3-flash"
    write_line "LLM_API_KEY = "
    write_line "GEMINI_API_KEY = "

    echo "---- Note start ----"
    echo "Get your Gemini API key at https://aistudio.google.com/app/api-keys"
    echo "Most of the features do not require a LLM backend,"
    echo "so you can skip this right now and fill it in later"
    echo "----  Note end  ----"

    echo "Sinopac configuration generated at $OUTPUT_PATH"
}
function generate_fubon_config() {
    write_line "# Broker-specific configuration. Fubon has no sandbox: every order is real."
    write_line "FUBON_PERSONAL_ID = "
    write_line "# FUBON_API_KEY for an API-key login, or FUBON_PASSWORD for a password login."
    write_line "FUBON_API_KEY = "
    write_line "FUBON_CERT_PATH = "
    write_line "FUBON_CERT_PASSWORD = "
    write_line "# Optional: the account number to trade, if the login returns several."
    write_line "FUBON_ACCOUNT = "
    write_line ""
    echo "---- Note start ----"
    echo "Apply for Fubon Trade API access and get your certificate at https://www.fbs.com.tw/TradeAPI/"
    echo "----  Note end  ----"
    echo "Fubon configuration generated at $OUTPUT_PATH"
}

if [ -z "$TEMPLATE" ]; then
    echo "Usage: $0 <template>"
    echo "Supported templates: [arenax, sinopac, fubon]"
    exit 1
fi

function main() {
    create_file
    if [ "$TEMPLATE" == "sinopac" ]; then
        generate_sinopac_config
    elif [ "$TEMPLATE" == "fubon" ]; then
        generate_fubon_config
    elif [ "$TEMPLATE" == "arenax" ]; then
        generate_arenax_config
    else
        echo "Unsupported template: $TEMPLATE"
        exit 1
    fi
}

main
